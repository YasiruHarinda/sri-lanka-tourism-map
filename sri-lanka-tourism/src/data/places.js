// Turns [11, 12, 1, 2] into "Nov – Feb", handling ranges that wrap around the year.
export function formatMonths(months) {
  if (months.length === 12) return 'Year-round';
  const set = new Set(months);
  const next = (m) => (m % 12) + 1;
  const prev = (m) => ((m + 10) % 12) + 1;
  const ranges = [];
  for (let m = 1; m <= 12; m++) {
    if (!set.has(m) || set.has(prev(m))) continue; // only start at the first month of a run
    let end = m;
    while (set.has(next(end))) end = next(end);
    ranges.push(end === m ? MONTHS[m - 1] : `${MONTHS[m - 1]} – ${MONTHS[end - 1]}`);
  }
  return ranges.join(', ');
}
